import { useEffect, useRef, useState, type ReactNode } from 'react'

// Wraps content in a fade-up that triggers once when it scrolls into view.
// Pure CSS transition (see `.reveal` in index.css); this only toggles the
// class via IntersectionObserver and disconnects after the first reveal.
type RevealProps = {
  children: ReactNode
  /** Optional stagger, in ms, applied as transition-delay. */
  delay?: number
  className?: string
}

export default function Reveal({ children, delay = 0, className = '' }: RevealProps) {
  const ref = useRef<HTMLDivElement>(null)
  const [visible, setVisible] = useState(false)

  useEffect(() => {
    const el = ref.current
    if (!el) return
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setVisible(true)
          io.disconnect()
        }
      },
      { threshold: 0.15, rootMargin: '0px 0px -10% 0px' },
    )
    io.observe(el)
    return () => io.disconnect()
  }, [])

  return (
    <div
      ref={ref}
      className={`reveal ${visible ? 'is-visible' : ''} ${className}`}
      style={delay ? { transitionDelay: `${delay}ms` } : undefined}
    >
      {children}
    </div>
  )
}
